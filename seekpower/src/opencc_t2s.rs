//! Fixed OpenCC 1.1.9 t2s compatibility implementation, not the complete OpenCC API.
//! Dictionary and matching semantics derive from BYVoid/OpenCC (Apache-2.0),
//! commit 556ed22496d650bd0b13b6c163be9814637970ae. See data/opencc-1.1.9.
//! t2s uses longest phrase matching followed by first-choice character mappings.
//! Because all character keys are single scalars, unmatched segments can be
//! converted in one pass without crossing a phrase boundary. No regional rules.
use std::{borrow::Cow, collections::HashMap, sync::LazyLock};

struct Dictionary {
    phrases: HashMap<char, Vec<(&'static str, &'static str)>>,
    characters: HashMap<char, &'static str>,
}
static DICTIONARY: LazyLock<Dictionary> = LazyLock::new(|| {
    let mut phrases: HashMap<char, Vec<(&str, &str)>> = HashMap::new();
    let mut characters = HashMap::new();
    for line in include_str!("../data/opencc-1.1.9/TSPhrases.txt").lines() {
        let (key, values) = line.split_once('\t').expect("pinned phrase dictionary");
        let value = values.split_whitespace().next().unwrap();
        assert!(!key.chars().any(|c| c.is_ascii()));
        assert!(!value.chars().any(|c| c.is_ascii()));
        phrases
            .entry(key.chars().next().unwrap())
            .or_default()
            .push((key, value));
    }
    for entries in phrases.values_mut() {
        entries.sort_unstable_by(|a, b| b.0.len().cmp(&a.0.len()).then_with(|| a.0.cmp(b.0)));
    }
    for line in include_str!("../data/opencc-1.1.9/TSCharacters.txt").lines() {
        let (key, values) = line.split_once('\t').expect("pinned character dictionary");
        let mut chars = key.chars();
        let ch = chars.next().unwrap();
        assert!(chars.next().is_none() && !ch.is_ascii());
        let value = values.split_whitespace().next().unwrap();
        assert!(!value.chars().any(|c| c.is_ascii()));
        characters.insert(ch, value);
    }
    Dictionary {
        phrases,
        characters,
    }
});

pub(crate) fn convert(text: &str) -> Cow<'_, str> {
    if text.is_ascii() {
        return Cow::Borrowed(text);
    }
    let dictionary = &*DICTIONARY;
    let mut output = String::with_capacity(text.len());
    let mut offset = 0;
    while offset < text.len() {
        let remaining = &text[offset..];
        let ch = remaining.chars().next().unwrap();
        if let Some((key, value)) = dictionary
            .phrases
            .get(&ch)
            .and_then(|entries| entries.iter().find(|(key, _)| remaining.starts_with(key)))
        {
            output.push_str(value);
            offset += key.len();
        } else {
            if let Some(value) = dictionary.characters.get(&ch) {
                output.push_str(value);
            } else {
                output.push(ch);
            }
            offset += ch.len_utf8();
        }
    }
    // Unlike the C-string API, preserve embedded NUL and all following text.
    // ASCII query syntax is never consumed or generated by the pinned tables.
    Cow::Owned(output)
}

#[cfg(test)]
mod tests {
    #[test]
    fn embedded_nul_preserves_and_converts_the_entire_suffix() {
        for (input, expected) in [
            ("臺灣\0頭髮", "台湾\0头发"),
            ("\0頭髮\0後綴\0", "\0头发\0后缀\0"),
            ("ascii\0suffix", "ascii\0suffix"),
        ] {
            assert_eq!(super::convert(input).as_bytes(), expected.as_bytes());
        }
    }
}
