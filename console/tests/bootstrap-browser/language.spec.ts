import { test, expect } from '@playwright/test';
const collection={id:'docs',name:'中文资料',schema:[{field:'body',field_type:'Text',store:true}],indexed_doc_count:1,version:'1',statistics:{},limits:{}};
test('switching preserves drafts and pending requests; reload remembers language',async({page})=>{
  let calls=0;
  await page.route('**/api/v1/**',async route=>{calls++;await route.fulfill({json:[collection]});});
  await page.goto('/');
  await page.getByLabel('Tenant API Key',{exact:true}).fill('test-key');
  await page.getByLabel('语言 / Language').selectOption('en');
  await expect(page).toHaveTitle('AnySeek · Semantic Space');
  await expect(page.locator('html')).toHaveAttribute('lang','en');
  await expect(page.getByLabel('Tenant API Key',{exact:true})).toHaveValue('test-key');
  await page.getByRole('button',{name:'Connect',exact:true}).click();
  await expect(page.getByRole('heading',{name:'All collections'})).toBeVisible();
  await page.evaluate(()=>sessionStorage.setItem('pendingWrites','{"owner":"other","requests":[]}'));
  await page.getByRole('button',{name:'Create collection',exact:true}).click();
  await page.getByLabel('Collection name',{exact:true}).fill('my_draft');
  const before=calls;
  await expect(page.locator('.language-switch')).toHaveCount(1);
  await expect(page.getByRole('dialog').locator('.language-switch')).toHaveCount(0);
  await expect(page.getByLabel('Collection name',{exact:true})).toHaveValue('my_draft');
  expect(calls).toBe(before);
  expect(await page.evaluate(()=>sessionStorage.getItem('pendingWrites'))).toBe('{"owner":"other","requests":[]}');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByLabel('语言 / Language').selectOption('en');
  await page.reload();
  await expect(page).toHaveTitle('AnySeek · Semantic Space');
  await expect(page.locator('.collection-name')).toContainText('中文资料');
  await page.getByRole('button',{name:'Schema',exact:true}).click();
  await expect(page.getByRole('dialog').locator('th').filter({hasText:/^Data type$/})).toBeVisible();
});
test('switching leaves search input unchanged',async({page})=>{
  await page.route('**/api/v1/**',route=>route.fulfill({json:[collection]}));
  await page.goto('/');
  await page.getByLabel('Tenant API Key',{exact:true}).fill('test-key');
  await page.getByRole('button',{name:'连接服务',exact:true}).click();
  await page.getByRole('button',{name:'检索调试',exact:true}).click();
  const input=page.locator('.search-entry input');
  await input.fill('中文查询');
  await page.getByLabel('语言 / Language').selectOption('en');
  await expect(input).toHaveValue('中文查询');
});
test('mobile language switching works with storage disabled',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new Error('blocked');};});
  await page.getByLabel('语言 / Language').selectOption('en');
  await expect(page.locator('.topbar').getByLabel('语言 / Language')).toHaveValue('en');
  await expect(page.locator('.sidebar .language-switch')).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
